#!/usr/bin/env node
/**
 * Writes lib/dial-codes.ts: every region libphonenumber-js knows, with its calling code.
 *
 *   node scripts/generate-dial-codes.mjs
 *
 * The phone field needs only this list, so it ships a few kilobytes instead of the
 * library's metadata. Numbers are still checked with the full library on the server
 * (lib/lead-context.ts). Re-run after upgrading libphonenumber-js.
 */
import { writeFileSync } from 'node:fs';
import { getCountries, getCountryCallingCode } from 'libphonenumber-js/core';
import metadata from 'libphonenumber-js/metadata.min.json';

const rows = getCountries(metadata).map((c) => `  ['${c}', '${getCountryCallingCode(c, metadata)}'],`);
const out = `/**
 * Region code and international calling code for every region libphonenumber-js knows.
 * Generated by scripts/generate-dial-codes.mjs; do not edit by hand.
 */
export const DIAL_CODES: ReadonlyArray<readonly [region: string, callingCode: string]> = [
${rows.join('\n')}
];
`;
writeFileSync(new URL('../lib/dial-codes.ts', import.meta.url), out);
console.log(`${rows.length} regions -> lib/dial-codes.ts`);
