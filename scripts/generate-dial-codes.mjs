#!/usr/bin/env node
/**
 * Writes lib/dial-codes.ts: every region libphonenumber-js knows, with its calling code
 * and English name, sorted by name.
 *
 *   node scripts/generate-dial-codes.mjs
 *
 * The phone field needs only this list, so it ships a few kilobytes instead of the
 * library's metadata. Numbers are still checked with the full library on the server
 * (lib/lead-context.ts). Re-run after upgrading libphonenumber-js.
 *
 * The names are written into the file rather than looked up with Intl.DisplayNames in
 * the component: Node and each browser ship different ICU data ("Falkland Islands" on
 * one, "Falkland Islands (Islas Malvinas)" on another), so a lookup during render gave
 * the server and the browser different text, a hydration error on every form page, and
 * React re-rendering the whole page in the browser.
 */
import { writeFileSync } from 'node:fs';
import { getCountries, getCountryCallingCode } from 'libphonenumber-js/core';
import metadata from 'libphonenumber-js/metadata.min.json';

const names = new Intl.DisplayNames(['en'], { type: 'region' });
const rows = getCountries(metadata)
  .map((c) => ({ c, code: getCountryCallingCode(c, metadata), name: names.of(c) ?? c }))
  .sort((a, b) => a.name.localeCompare(b.name, 'en'))
  .map(({ c, code, name }) => `  ['${c}', '${code}', ${JSON.stringify(name)}],`);
const out = `/**
 * Region code, international calling code and English name for every region
 * libphonenumber-js knows, sorted by name. Generated by scripts/generate-dial-codes.mjs;
 * do not edit by hand. The names are fixed here, not looked up at render, so the server
 * and the browser render the same list (the script explains why).
 */
export const DIAL_CODES: ReadonlyArray<readonly [region: string, callingCode: string, name: string]> = [
${rows.join('\n')}
];
`;
writeFileSync(new URL('../lib/dial-codes.ts', import.meta.url), out);
console.log(`${rows.length} regions -> lib/dial-codes.ts`);
